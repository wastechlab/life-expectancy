// Turns data/algorithm.json and data/countries.json into a TypeScript module the library compiles with.
// The data stays JSON so that people who propose a change never have to touch code, while the published
// package carries plain ES modules: no consumer has to support importing JSON. Typing the values on the way
// also makes the compiler check the data against the library's own types.
//
//   npm run build-data
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (name: string): string => JSON.stringify(JSON.parse(readFileSync(`${root}data/${name}`, 'utf8')), null, 2);

const module = [
    '// Generated by scripts/build-data.ts from data/algorithm.json and data/countries.json. Edit the JSON instead.',
    "import type { Algorithm, CountryFigures } from '../types.js';",
    '',
    `export const ALGORITHM: Algorithm = ${read('algorithm.json')};`,
    '',
    `export const COUNTRIES: readonly CountryFigures[] = ${read('countries.json')};`,
    '',
].join('\n');

mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(`${root}src/generated/data.ts`, module);
